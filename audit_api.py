import urllib.request, json
r = urllib.request.urlopen('http://127.0.0.1:8766/api/dashboard', timeout=10)
d = json.loads(r.read())
print('=== TOP-LEVEL KEYS ===')
print(list(d.keys()))
print()
print('=== SUMMARY ===')
print(json.dumps(d['summary'], indent=2))
print()
print('=== POLICY ===')
print(json.dumps(d.get('policy', {}), indent=2))
print()
print('=== ALL SERVICES ===')
for i, s in enumerate(d['services']):
    print(f'--- [{i}] ---')
    print(f'id: {s.get("id")}')
    print(f'service: {s.get("service")}')
    print(f'project: {s.get("project")}')
    print(f'runtime: {s.get("runtime")}')
    print(f'risk: {s.get("risk")}')
    print(f'cpu_probability: {s.get("cpu_probability")}')
    print(f'memory_probability: {s.get("memory_probability")}')
    print(f'cpu_alarm: {s.get("cpu_alarm")}')
    print(f'memory_alarm: {s.get("memory_alarm")}')
    print(f'action: {s.get("action")}')
    print(f'state: {s.get("state")}')
    print(f'warning_time: {s.get("historical_warning_minutes")}')
    print(f'history_len: {len(s.get("history", []))}')
    print(f'feature_contributions keys: {list(s.get("feature_contributions", {}).keys())}')
    print(f'shapley_phi keys: {list(s.get("shapley_phi_values", {}).keys())}')
    print(f'sre_runbook_steps len: {len(s.get("sre_runbook_steps", []))}')
    print(f'rca_narrative: {repr(s.get("rca_narrative"))[:120]}')
    print(f'warning_message: {repr(s.get("warning_message"))[:120]}')
    print(f'mitigation_executed: {json.dumps(s.get("mitigation_executed", {}))[:200]}')
    print(f'incident_ticket: {json.dumps(s.get("incident_ticket_payload", {}))[:200]}')
    print(f'prediction_time: {s.get("prediction_time")}')
print()
print('=== RELIABILITY ===')
rel = d.get('reliability', {})
print(list(rel.keys()))
print('cpu_lopo rows:', len(rel.get('cpu_lopo', [])))
print('memory_lopo rows:', len(rel.get('memory_lopo', [])))
